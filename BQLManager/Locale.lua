function Addon:Text(key, ...)
    key = tostring(key or "")
    local translations = self.IS_SPANISH and SPANISH or ENGLISH
    local text = translations[key] or key
    if select("#", ...) > 0 then
        return format(text, ...)
    end
    return text
end
